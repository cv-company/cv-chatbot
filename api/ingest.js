export default async function handler(req, res) {
  const key = (req.query && req.query.key) || '';
  if (key !== INGEST_KEY) return res.status(401).json({ error: 'unauthorized. URLの末尾に ?key=cvfaq2026setup を付けてください' });

  const url = process.env.UPSTASH_VECTOR_REST_URL;
  const token = process.env.UPSTASH_VECTOR_REST_TOKEN;
  if (!url || !token) {
    return res.status(500).json({ error: 'Upstash の環境変数が設定されていません', hasUrl: !!url, hasToken: !!token });
  }

  try {
    const records = FAQ.map((e) => ({
      id: e.id,
      data: `質問: ${e.question}\n回答: ${e.answer}`,
      metadata: { category: e.category, question: e.question, answer: e.answer },
    }));

    // 20件ずつのまとまりに分けて「同時に」登録（速い＝タイムアウトしない）
    const CHUNK = 20;
    const batches = [];
    for (let i = 0; i < records.length; i += CHUNK) batches.push(records.slice(i, i + CHUNK));

    const results = await Promise.all(
      batches.map(async (slice) => {
        const r = await fetch(`${url}/upsert-data`, {
          method: 'POST',
          headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
          body: JSON.stringify(slice),
        });
        const text = await r.text();
        return { ok: r.ok, status: r.status, text };
      })
    );

    const failed = results.find((x) => !x.ok);
    if (failed) {
      return res.status(500).json({ error: 'Upstashへの登録に失敗しました', status: failed.status, detail: failed.text });
    }

    return res.status(200).json({ ok: true, upserted: records.length });
  } catch (e) {
    return res.status(500).json({ error: String((e && e.message) || e) });
  }
}
